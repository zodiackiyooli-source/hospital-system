const Joi = require('joi');

const patientSchema = Joi.object({
  full_name: Joi.string().required().messages({
    'string.empty': 'Full name waa muhiim',
    'any.required': 'Full name waa laga baqaa'
  }),
  gender: Joi.string().valid('Male', 'Female', 'Other').required().messages({
    'any.only': 'Gender waa nabad lahayd: Male, Female, ama Other',
    'any.required': 'Gender waa laga baqaa'
  }),
  age: Joi.object({
    value: Joi.number().min(0).required(),
    unit: Joi.string().valid('Year', 'Month', 'Week', 'Day', 'Hour').required()
  }).required().messages({
    'any.required': 'Age waa lagu baqaa'
  }),
  phone: Joi.string().pattern(/^\+?[\d\s\-\(\)]{10,15}$/).required().messages({
    'string.pattern.base': 'Phone number qaab xun',
    'string.empty': 'Phone waa muhiim',
    'any.required': 'Phone waa laga baqaa'
  }),
  address: Joi.string().min(5).required().messages({
    'string.min': 'Address waa ugu yaraan 5 characters',
    'string.empty': 'Address waa muhiim', 
    'any.required': 'Address waa laga baqaa'
  }),
  blood_group: Joi.string().valid('A+', 'A-', 'B+', 'B-', 'AB+', 'AB-', 'O+', 'O-').required().messages({
    'any.only': 'Blood group waa: A+, A-, B+, B-, AB+, AB-, O+, O-',
    'any.required': 'Blood group waa laga baqaa'
  }),
  illness_duration: Joi.object({
    value: Joi.number().min(0).default(0),
    unit: Joi.string().valid('Year', 'Month', 'Week', 'Day', 'Hour').default('Day')
  }).optional(),
  history: Joi.string().allow('').default(''),
  medical_record: Joi.string().allow('').default(''),
  patient_id: Joi.string().optional() // Auto-generated by model
});

const validatePatient = (req, res, next) => {
  const { error } = patientSchema.validate(req.body, { abortEarly: false });
  
  if (error) {
    const messages = error.details.map(detail => detail.message).join(', ');
    return res.status(400).json({
      success: false,
      message: 'Validation error: ' + messages
    });
  }
  
  next();
};

module.exports = { validatePatient, patientSchema };
